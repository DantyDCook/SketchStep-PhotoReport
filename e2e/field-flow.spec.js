import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {zipSync,unzipSync,strToU8,strFromU8} from 'fflate';
test('synthetic album import, bulk assignment, PDF and backup round trip',async({page})=>{
 await page.goto('http://127.0.0.1:4173/');
 await expect(page.locator('#galleryCount')).toHaveText('0 of 0 photos shown');
 const png=async color=>Buffer.from(await page.evaluate(async color=>{
  const c=document.createElement('canvas');c.width=120;c.height=80;const ctx=c.getContext('2d');ctx.fillStyle=color;ctx.fillRect(0,0,120,80);
  const blob=await new Promise(r=>c.toBlob(r,'image/png'));return Array.from(new Uint8Array(await blob.arrayBuffer()));
 },color));
 const first=await png('#234567'),second=await png('#abcdef');
 const zip=Buffer.from(zipSync({'Synthetic/IMG_2.png':first,'Synthetic/IMG_10.png':second,'Synthetic/duplicate.png':first,'Synthetic/IMG_2.png.json':strToU8(JSON.stringify({title:'IMG_2.png',photoTakenTime:{timestamp:'1764000000'}}))}));
 await page.locator('#files').setInputFiles({name:'synthetic.zip',mimeType:'application/zip',buffer:zip});
 await expect(page.locator('#status')).toContainText('2 imported');
 await expect(page.locator('#galleryCount')).toHaveText('2 of 2 photos shown');
 await expect(page.locator('#photos')).toContainText('Google Photos photoTakenTime');
 await page.locator('#customer').fill('Synthetic field test');
 await page.locator('#selectVisible').click();
 await page.locator('#bulkPanel summary').click();
 await page.locator('#bulkSetfloor').check();await page.locator('#bulkValuefloor').fill('Floor 2');
 await page.locator('#bulkSetroom').check();await page.locator('#bulkValueroom').fill('Kitchen');
 page.once('dialog',d=>d.accept());await page.locator('#bulkApply').click();
 await expect(page.locator('#status')).toContainText('Updated 2 photographs');
 await page.locator('#filterFloor').selectOption('Floor 2');
 await page.locator('#filterRoom').selectOption('Kitchen');
 await expect(page.locator('#galleryCount')).toHaveText('2 of 2 photos shown');
 await page.locator('#viewSort').selectOption('name');
 await expect(page.locator('#photos article').first()).toContainText('IMG_2.png');
 const pdfEvent=page.waitForEvent('download');await page.locator('#pdf').click();const pdf=await pdfEvent;
 expect((await readFile(await pdf.path())).subarray(0,5).toString()).toBe('%PDF-');
 await expect(page.locator('#status')).toContainText('PDF generated: 2');
 const backupEvent=page.waitForEvent('download');await page.locator('#backup').click();const backup=await backupEvent;
 const backupBytes=await readFile(await backup.path());const manifest=JSON.parse(strFromU8(unzipSync(backupBytes)['manifest.json']));
 expect(manifest.photos).toHaveLength(2);expect(manifest.photos.every(p=>p.floor==='Floor 2'&&p.room==='Kitchen')).toBeTruthy();
 page.once('dialog',d=>d.accept());await page.locator('#clear').click();await expect(page.locator('#galleryCount')).toHaveText('0 of 0 photos shown');
 page.once('dialog',d=>d.accept());await page.locator('#restore').setInputFiles({name:'backup.zip',mimeType:'application/zip',buffer:backupBytes});
 await expect(page.locator('#status')).toContainText('Restored 2 photos');
 await page.reload();await expect(page.locator('#galleryCount')).toHaveText('2 of 2 photos shown');
 await expect(page.locator('#photos')).toContainText('Floor 2');
});
